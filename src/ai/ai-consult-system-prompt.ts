export const buildSessionContextPrompt = (
  session: Array<{ role: 'user' | 'assistant'; content: string }>,
) => `
История диалога:
${session
  .slice(-8)
  .map((m) => `${m.role.toUpperCase()}: ${m.content}`)
  .join('\n')}
`;

